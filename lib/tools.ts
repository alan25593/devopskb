  id: string
  label: string
  description: string
  href: string
  iconPath: string
  group: string
  badges?: string[]
  status?: 'Stable' | 'Beta' | 'Nuevo'
  /** Guides shown as "Aprendé más" on the tool and that link back to it, as "category/slug" */
